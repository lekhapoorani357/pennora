class PennoraPDF(FPDF):
    """Custom FPDF layout with Pennora header, footer, and branding."""

    def header(self):
        self.set_fill_color(15, 23, 42)  # Dark slate navy
        self.rect(0, 0, 210, 16, "F")
        self.set_xy(10, 5)
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(255, 255, 255)
        self.cell(120, 6, "PENNORA  |  FINANCIAL HEALTH & GROWTH REPORT", 0, 0, "L")
        self.set_font("Helvetica", "I", 8)
        self.cell(70, 6, "CONFIDENTIAL & PROPRIETARY", 0, 1, "R")
        self.set_y(22)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(148, 163, 184)  # Slate light
        self.cell(
            0,
            5,
            f"Page {self.page_no()} of {{nb}}  |  Generated by Pennora Intelligence  |  Educational Planning Tool - Not SEBI/Tax Advisory",
            0,
            0,
            "C",
        )


def collect_report_data(user_id: str) -> Dict[str, Any]:
    """Collects real user profile, goals, transactions, and tax calculations.

    Missing fields are explicitly kept as None to prevent fabrication.
    """
    users_coll = get_collection("users")
    user = users_coll.find_one({"_id": str(user_id)}) or {}

    profiles_coll = get_collection("financial_profiles")
    profile = profiles_coll.find_one({"userId": str(user_id)}) or {}

    goals_coll = get_collection("goals")
    raw_goals = goals_coll.find({"userId": str(user_id)}) or []
    goals_list = []
    total_target = 0.0
    total_saved = 0.0
    for g in raw_goals:
        target = float(g.get("targetAmount", 0.0) or 0.0)
        current = float(g.get("currentAmount", 0.0) or 0.0)
        total_target += target
        total_saved += current
        pct = round((current / target * 100), 1) if target > 0 else 0.0
        goals_list.append({
            "title": g.get("title", g.get("name", "Goal")),
            "targetAmount": target,
            "currentAmount": current,
            "progressPercent": pct,
            "category": g.get("category", "General"),
        })

    # Financial Profile Metrics (strictly real data)
    monthly_income = profile.get("monthlyIncome")
    monthly_income = float(monthly_income) if monthly_income is not None else None

    monthly_expenses = profile.get("monthlyExpenses")
    monthly_expenses = float(monthly_expenses) if monthly_expenses is not None else None

    savings_rate = None
    if monthly_income and monthly_income > 0 and monthly_expenses is not None:
        savings = monthly_income - monthly_expenses
        savings_rate = round((savings / monthly_income * 100), 1)

    # Health score composite (heuristic based solely on available real data)
    health_score = None
    if monthly_income is not None:
        score = 50.0
        if savings_rate is not None:
            if savings_rate >= 30:
                score += 25.0
            elif savings_rate >= 15:
                score += 15.0
            elif savings_rate > 0:
                score += 5.0
        if goals_list:
            score += 15.0
        health_score = int(min(100.0, max(0.0, score)))

    # Deterministic Tax Summary
    annual_income = (monthly_income * 12.0) if monthly_income is not None else 0.0
    t_input = TaxInput(gross_salary=annual_income, financial_year=DEFAULT_TAX_YEAR)
    tax_result = calculate_tax(t_input)

    return {
        "userId": str(user_id),
        "fullName": user.get("fullName", user.get("name", "Pennora Member")),
        "email": user.get("email", "Not available"),
        "monthlyIncome": monthly_income,
        "monthlyExpenses": monthly_expenses,
        "savingsRate": savings_rate,
        "healthScore": health_score,
        "goals": goals_list,
        "totalGoalsTarget": total_target if goals_list else None,
        "totalGoalsSaved": total_saved if goals_list else None,
        "taxResult": tax_result,
        "asOfDate": datetime.now(timezone.utc).strftime("%d %B %Y"),
    }


