def purchase_report(user_id: str, is_demo: bool = True) -> Dict[str, Any]:
    """Records a report purchase, creating payment, revenue, and report entries."""
    users_coll = get_collection("users")
    user = users_coll.find_one({"_id": str(user_id)})
    if not user:
        raise ValueError(f"User {user_id} not found.")

    report_id = generate_id()
    payment_id = generate_id()
    amount = 499.0

    # 1. Create Payment record
    payments_coll = get_collection("payments")
    payment_doc = {
        "_id": payment_id,
        "userId": str(user_id),
        "amount": amount,
        "currency": "INR",
        "planCode": "financial_report_v1",
        "paymentMethod": "demo" if is_demo else "card",
        "status": "paid",
        "taxAmount": round(amount * 0.18, 2),
        "netAmount": round(amount * 0.82, 2),
        "isDemo": is_demo,
        "createdAt": utc_now(),
        "updatedAt": utc_now(),
    }
    payments_coll.insert_one(payment_doc)

    # 2. Record Revenue Event (separated demo vs real)
    rev_coll = get_collection("revenue_events")
    rev_doc = {
        "_id": generate_id(),
        "userId": str(user_id),
        "revenueSource": "PREMIUM_FEATURE",
        "eventType": "report_purchase",
        "amount": amount,
        "taxAmount": round(amount * 0.18, 2),
        "netRevenue": round(amount * 0.82, 2),
        "currency": "INR",
        "status": "COMPLETED",
        "isDemo": is_demo,
        "createdAt": utc_now(),
    }
    rev_coll.insert_one(rev_doc)

    # 3. Create Report record
    reports_coll = get_collection("financial_reports")
    report_doc = {
        "_id": report_id,
        "userId": str(user_id),
        "reportType": "financial_health_growth",
        "status": "pending",
        "pdfBytes": None,
        "purchaseId": payment_id,
        "isDemo": is_demo,
        "summaryJson": None,
        "generatedAt": None,
        "asOfDate": utc_now(),
        "createdAt": utc_now(),
        "updatedAt": utc_now(),
    }
    reports_coll.insert_one(report_doc)

    return report_doc


def generate_and_store_report(user_id: str, report_id: str) -> Dict[str, Any]:
    """Generates the PDF report for the user and stores base64 payload in the database."""
    reports_coll = get_collection("financial_reports")
    report = reports_coll.find_one({"_id": str(report_id)})
    if not report:
        raise ValueError(f"Report {report_id} not found.")

    if str(report["userId"]) != str(user_id):
        raise PermissionError("Access denied: You can only generate your own reports.")

    # Collect data & generate real PDF
    data = collect_report_data(user_id)
    pdf_bytes = generate_pdf_report(data)

    # Encode to base64
    b64_pdf = base64.b64encode(pdf_bytes).decode("ascii")

    summary = {
        "healthScore": data["healthScore"],
        "monthlyIncome": data["monthlyIncome"],
        "savingsRate": data["savingsRate"],
        "recommendedRegime": data["taxResult"].recommended_regime,
        "taxSavings": data["taxResult"].tax_savings,
    }

    now = utc_now()
    reports_coll.update_one(
        {"_id": str(report_id)},
        {
            "$set": {
                "status": "completed",
                "pdfBytes": b64_pdf,
                "summaryJson": json.dumps(summary),
                "generatedAt": now,
                "updatedAt": now,
            }
        },
    )

    updated_report = reports_coll.find_one({"_id": str(report_id)})
    return updated_report
